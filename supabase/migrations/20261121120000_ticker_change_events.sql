-- Shared ticker-change history for Short Check and later apps.
-- Seed: data/ticker_changes_36m_filtered.xlsx (203 events, 2023-12-19 through 2026-11-16).
-- In that sheet, ticker is the symbol after the change and event_ticker is the symbol before it.
-- Reads are public. Writes are service-role only.

create table if not exists public.ticker_change_events (
  id bigint generated always as identity primary key,
  old_ticker text not null,
  new_ticker text not null,
  effective_date date not null,
  issuer_name text,
  cik text,
  security_id text,
  source text not null,
  created_at timestamptz not null default now(),
  constraint ticker_change_events_pair unique (old_ticker, new_ticker, effective_date),
  constraint ticker_change_events_old_symbol check (old_ticker ~ '^[A-Z0-9.\-^]{1,6}$'),
  constraint ticker_change_events_new_symbol check (new_ticker ~ '^[A-Z0-9.\-^]{1,6}$')
);

create index if not exists ticker_change_events_old_idx
  on public.ticker_change_events (old_ticker);
create index if not exists ticker_change_events_new_idx
  on public.ticker_change_events (new_ticker);
create index if not exists ticker_change_events_security_idx
  on public.ticker_change_events (security_id);

create table if not exists public.ticker_change_lookups (
  ticker text primary key,
  has_changes boolean not null,
  checked_at timestamptz not null default now(),
  source text not null,
  constraint ticker_change_lookups_symbol check (ticker ~ '^[A-Z0-9.\-^]{1,6}$')
);

alter table public.ticker_change_events enable row level security;
alter table public.ticker_change_lookups enable row level security;

grant select on public.ticker_change_events to anon, authenticated;
grant select on public.ticker_change_lookups to anon, authenticated;
grant select, insert, update, delete on public.ticker_change_events to service_role;
grant select, insert, update, delete on public.ticker_change_lookups to service_role;

drop policy if exists ticker_change_events_read on public.ticker_change_events;
create policy ticker_change_events_read
  on public.ticker_change_events
  for select
  to anon, authenticated
  using (true);

drop policy if exists ticker_change_lookups_read on public.ticker_change_lookups;
create policy ticker_change_lookups_read
  on public.ticker_change_lookups
  for select
  to anon, authenticated
  using (true);

